/**
 * TikZ Korean & Unicode Text Support Engine for TikZJax
 *
 * TikZJax runs an in-browser WebAssembly TeX82 engine that does not natively bundle
 * CJK/Korean font metrics (TFM) or LaTeX packages (kotex/CJKutf8).
 * 
 * This module seamlessly solves the limitation by:
 * 1. Pre-processing: Scanning TikZ code for Korean/CJK/Unicode text (e.g. {ㄱ}, {시작점}, {밑변})
 *    and replacing them with width-proportional, collision-safe ASCII tokens (e.g. TZK0P, TZK1PX).
 * 2. Compilation: Feeding the safe ASCII TikZ code to TikZJax's TeX engine so compilation succeeds with 0 errors.
 * 3. Post-processing: Intercepting the generated SVG output (both DOM and string formats),
 *    restoring the original Korean text into the respective <text> elements, and assigning crisp
 *    Korean typography fonts ('Noto Sans KR', 'Noto Serif KR', sans-serif).
 */

export interface TikZReplacement {
  placeholder: string;
  originalText: string;
  entityLower: string; // e.g. "&#xf054;&#xf05a;&#xf04b;&#xf030;&#xf050;"
  entityUpper: string; // e.g. "&#xF054;&#xF05A;&#xF04B;&#xF030;&#xF050;"
  domPattern: string;  // e.g. "\uF054\uF05A\uF04B\uF030\uF050"
}

export interface PreparedTikZResult {
  code: string;
  replacements: TikZReplacement[];
  hasKorean: boolean;
}

// Regex to capture non-ASCII character sequences (Korean Hangul, Jamo, Hanja, circled numbers)
// including single spaces between non-ASCII words
const NON_ASCII_TEXT_REGEX = /[^\x00-\x7F]+(?:\s+[^\x00-\x7F]+)*/gu;

/**
 * Checks whether the given code contains any Korean or non-ASCII characters.
 */
export function hasKoreanCharacters(code: string): boolean {
  if (!code) return false;
  return /[^\x00-\x7F]/.test(code);
}

/**
 * Transforms TikZ code containing Korean/Unicode text into TeX-safe ASCII code
 * by swapping non-ASCII sequences with deterministic placeholders.
 */
export function prepareTikZWithKorean(rawCode: string): PreparedTikZResult {
  if (!rawCode || !hasKoreanCharacters(rawCode)) {
    return {
      code: rawCode,
      replacements: [],
      hasKorean: false
    };
  }

  const replacements: TikZReplacement[] = [];
  let counter = 0;

  const transformedCode = rawCode.replace(NON_ASCII_TEXT_REGEX, (match) => {
    const idx = counter++;
    const base = `TZK${idx}P`;
    
    // In TeX Computer Modern fonts, 1 Korean character is approximately ~1em wide,
    // while standard Latin characters are ~0.5em wide.
    // Matching 2 ASCII letters per Korean character preserves the layout box size and alignments.
    const targetLen = Math.max(base.length, match.length * 2);
    const placeholder = base.padEnd(targetLen, 'X');

    // Build entity representations generated by TikZJax dvi2html
    const entityLower = Array.from(placeholder)
      .map((c) => `&#x${(0xf000 + c.charCodeAt(0)).toString(16).toLowerCase()};`)
      .join('');
    const entityUpper = Array.from(placeholder)
      .map((c) => `&#x${(0xf000 + c.charCodeAt(0)).toString(16).toUpperCase()};`)
      .join('');
    const domPattern = Array.from(placeholder)
      .map((c) => String.fromCharCode(0xf000 + c.charCodeAt(0)))
      .join('');

    replacements.push({
      placeholder,
      originalText: match,
      entityLower,
      entityUpper,
      domPattern
    });

    return placeholder;
  });

  return {
    code: transformedCode,
    replacements,
    hasKorean: replacements.length > 0
  };
}

/**
 * Restores Korean text in the rendered SVG DOM element.
 */
export function restoreKoreanInTikZElement(
  containerOrSvg: HTMLElement | SVGElement | null,
  replacements: TikZReplacement[]
): void {
  if (!containerOrSvg || !replacements || replacements.length === 0) return;

  const textNodes = Array.from(containerOrSvg.querySelectorAll('text'));
  
  for (const textEl of textNodes) {
    let textModified = false;
    let currentContent = textEl.textContent || '';

    for (const item of replacements) {
      if (
        currentContent.includes(item.domPattern) ||
        currentContent.includes(item.placeholder) ||
        currentContent.includes(item.entityLower) ||
        currentContent.includes(item.entityUpper)
      ) {
        currentContent = currentContent
          .split(item.domPattern).join(item.originalText)
          .split(item.placeholder).join(item.originalText)
          .split(item.entityLower).join(item.originalText)
          .split(item.entityUpper).join(item.originalText);
        textModified = true;
      }
    }

    if (textModified) {
      textEl.textContent = currentContent;
      // Apply clean, crisp Korean typography
      textEl.setAttribute('font-family', "'Noto Sans KR', 'Noto Serif KR', sans-serif");
      textEl.style.fontFamily = "'Noto Sans KR', 'Noto Serif KR', sans-serif";
      textEl.style.fontWeight = '500';
    }
  }

  // Also check innerHTML in case elements used direct entity text
  let inner = containerOrSvg.innerHTML;
  let innerChanged = false;
  for (const item of replacements) {
    if (inner.includes(item.entityLower) || inner.includes(item.entityUpper) || inner.includes(item.domPattern)) {
      inner = inner
        .split(item.entityLower).join(item.originalText)
        .split(item.entityUpper).join(item.originalText)
        .split(item.domPattern).join(item.originalText);
      innerChanged = true;
    }
  }

  if (innerChanged) {
    containerOrSvg.innerHTML = inner;
  }
}

/**
 * Restores Korean text in an SVG string (outerHTML) for caching and immediate display.
 */
export function restoreKoreanInTikZSvgString(
  svgString: string,
  replacements: TikZReplacement[]
): string {
  if (!svgString || !replacements || replacements.length === 0) return svgString;

  let restored = svgString;

  for (const item of replacements) {
    restored = restored
      .split(item.entityLower).join(item.originalText)
      .split(item.entityUpper).join(item.originalText)
      .split(item.domPattern).join(item.originalText)
      .split(item.placeholder).join(item.originalText);
  }

  // Set font-family on <text> elements containing Korean characters
  restored = restored.replace(/<text\b([^>]*)>([\s\S]*?)<\/text>/gi, (fullMatch, attrs, content) => {
    if (/[^\x00-\x7F]/.test(content)) {
      let updatedAttrs = attrs;
      if (/font-family="[^"]*"/i.test(updatedAttrs)) {
        updatedAttrs = updatedAttrs.replace(
          /font-family="[^"]*"/i,
          'font-family="\'Noto Sans KR\', \'Noto Serif KR\', sans-serif"'
        );
      } else {
        updatedAttrs += ' font-family="\'Noto Sans KR\', \'Noto Serif KR\', sans-serif"';
      }
      return `<text${updatedAttrs}>${content}</text>`;
    }
    return fullMatch;
  });

  return restored;
}
